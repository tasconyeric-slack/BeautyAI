// Generate web/lib/passport.ts from schema/passport.schema.json (which $refs analysis.schema.json).
// The analysis schema is inlined and its $defs hoisted to the root so every "#/$defs/..." ref resolves.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../schema");
const passport = JSON.parse(readFileSync(resolve(schemaDir, "passport.schema.json"), "utf8"));
const analysis = JSON.parse(readFileSync(resolve(schemaDir, "analysis.schema.json"), "utf8"));

const { $defs: analysisDefs = {}, $schema: _s, $id: _i, ...analysisBody } = analysis;
passport.$defs = { ...(passport.$defs ?? {}), ...analysisDefs };
passport.properties.analysis = { ...analysisBody, title: "Analysis" };
delete passport.$id;
passport.title = "Passport";

const ts = await compile(passport, "Passport", {
  bannerComment:
    "/* Generated by `make types` from schema/passport.schema.json — do not edit by hand. */",
  additionalProperties: false,
  unreachableDefinitions: true,
  ignoreMinAndMaxItems: true,
  style: { singleQuote: false },
});
// quick.schema.json and api.schema.json reference the analysis and passport schemas; point those refs at the
// TypeScript types generated above instead of inlining them a second time.
const pascal = (k) => k.replace(/(^|_)([a-z])/g, (_m, _u, c) => c.toUpperCase());
const relink = (node, map) => {
  if (Array.isArray(node)) return node.map((n) => relink(n, map));
  if (node && typeof node === "object") {
    if (typeof node.$ref === "string" && !node.$ref.startsWith("#")) {
      const ts = map(node.$ref);
      if (ts) return { tsType: ts };
    }
    return Object.fromEntries(Object.entries(node).map(([k, v]) => [k, relink(v, map)]));
  }
  return node;
};
const refMap = (ref) => {
  if (ref.startsWith("analysis.schema.json#/$defs/")) return pascal(ref.split("/").pop());
  if (ref === "passport.schema.json") return "Passport";
  if (ref.startsWith("passport.schema.json#/properties/")) return `Passport["${ref.split("/").pop()}"]`;
  if (ref === "quick.schema.json") return "QuickAnalysis";
  return null;
};
const extra = [];
for (const [file, title] of [["quick.schema.json", "QuickAnalysis"], ["api.schema.json", "PassportResponse"]]) {
  const raw = JSON.parse(readFileSync(resolve(schemaDir, file), "utf8"));
  delete raw.$id;
  delete raw.$schema;
  const schema = relink({ ...raw, title }, refMap);
  extra.push(await compile(schema, title, {
    bannerComment: `/* ${file} */`, additionalProperties: false, unreachableDefinitions: true,
    ignoreMinAndMaxItems: true, declareExternallyReferenced: true, style: { singleQuote: false },
  }));
}
writeFileSync(resolve(here, "../lib/passport.ts"), ts + "\n" + extra.join("\n"));
console.log("wrote web/lib/passport.ts (Passport, QuickAnalysis, PassportResponse)");
